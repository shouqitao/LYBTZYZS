        #endregion

        #region 边界条件测试

        [Fact]
        public void Mapping_WithNullSource_ShouldReturnNull()
        {
            // Arrange
            User? nullUser = null;

            // Act
            var dto = _mapper.Map<UserDto>(nullUser);

            // Assert
            dto.Should().BeNull();
        }

        [Fact]
        public void UserCreateDto_WithMinimalData_ShouldMapSuccessfully()
        {
            // Arrange
            var createDto = new UserInputDto
            {
                UserName = "minimal",
                RealName = "最小数据",
                Password = "Pass123!",
                ConfirmPassword = "Pass123!"
                // 其他字段为null
            };

            // Act
            var user = _mapper.Map<User>(createDto);

            // Assert
            user.Should().NotBeNull();
            user.UserName.Should().Be("minimal");
            user.RealName.Should().Be("最小数据");
            user.Email.Should().BeNull();
            user.PhoneNumber.Should().BeNull();
        }

        [Fact]
        public void UserUpdateDto_WithPartialData_ShouldMapOnlyProvidedFields()
        {
            // Arrange
            var updateDto = new UserInputDto
            {
                Id = Guid.NewGuid(),
                RealName = "部分更新",
                Email = "partial@test.com"
                // 其他字段为null
            };

            // Act
            var user = _mapper.Map<User>(updateDto);

            // Assert
            user.Should().NotBeNull();
            user.RealName.Should().Be("部分更新");
            user.Email.Should().Be("partial@test.com");
            user.PhoneNumber.Should().BeNull();
        }

        #endregion

        #region 特殊字符测试

        [Fact]
        public void User_To_UserDto_WithSpecialCharactersInName_ShouldMapCorrectly()
        {
            // Arrange
            var user = new User
            {
                Id = Guid.NewGuid(),
                UserName = "special_user",
                RealName = "欧阳·修",
                Email = "test+tag@example.com",
                Role = UserRole.Doctor,
                Status = CommonStatus.Enabled,
                PinYinCode = "OYX"
            };

            // Act
            var dto = _mapper.Map<UserDto>(user);

            // Assert
            dto.RealName.Should().Be("欧阳·修");
            dto.Email.Should().Be("test+tag@example.com");
            dto.PinYinCode.Should().Be("OYX");
        }

        #endregion
    }
}
