            // Assert
            config.AssertConfigurationIsValid();
        }

        #endregion

        #region Patient -> PatientDto 映射测试

        [Fact]
        public void Patient_To_PatientDto_ShouldMapCorrectly()
        {
            // Arrange
            var patient = new Patient
            {
                Id = Guid.NewGuid(),
                Name = "张三",
                Gender = Gender.Male,
                BirthDate = new DateTime(1980, 5, 15),
                PhoneNumber = "13800138000",
                IdNumber = "110101198005151234",
                Address = "北京市朝阳区某某街道",
                PinYinCode = "ZS",
                Status = CommonStatus.Enabled,
                VisitCount = 5,
                LastVisitTime = DateTime.Now.AddDays(-7),
                EmergencyContactName = "李四",
                EmergencyContactPhone = "13900139000",
                AllergyHistory = "青霉素",
                CreatedAt = DateTime.Now.AddYears(-2)
            };

            // Act
            var dto = _mapper.Map<PatientDto>(patient);

            // Assert
            dto.Should().NotBeNull();
            dto.Id.Should().Be(patient.Id);
            dto.Name.Should().Be(patient.Name);
            dto.Gender.Should().Be(patient.Gender);
            dto.BirthDate.Should().Be(patient.BirthDate);
            dto.PhoneNumber.Should().Be(patient.PhoneNumber);
            dto.IdNumber.Should().Be(patient.IdNumber);
            dto.Address.Should().Be(patient.Address);
            dto.PinYinCode.Should().Be(patient.PinYinCode);
            dto.Status.Should().Be(patient.Status);
            dto.EmergencyContactName.Should().Be(patient.EmergencyContactName);
            dto.EmergencyContactPhone.Should().Be(patient.EmergencyContactPhone);
            dto.AllergyHistory.Should().Be(patient.AllergyHistory);
        }

        [Fact]
        public void Patient_To_PatientDto_ShouldIgnoreAgeProperty()
        {
            // Arrange
            var patient = new Patient
            {
                Id = Guid.NewGuid(),
                Name = "测试患者",
                BirthDate = new DateTime(1990, 1, 1),
                Gender = Gender.Female,
                Status = CommonStatus.Enabled
            };

            // Act
            var dto = _mapper.Map<PatientDto>(patient);

            // Assert - Age 是计算属性，由 DTO 根据 BirthDate 自动计算
            dto.Age.Should().NotBeNull();
            dto.Age.Should().Be(DateTime.Today.Year - 1990); // 基于出生年份计算
        }

        #endregion

