        [Fact]
        public void PatientCreateDto_To_Patient_ShouldIgnoreAutoGeneratedFields()
        {
            // Arrange
            var createDto = new PatientInputDto
            {
                Name = "自动字段测试",
                Gender = Gender.Female,
                BirthDate = new DateTime(1995, 6, 10)
            };

            // Act
            var patient = _mapper.Map<Patient>(createDto);

            // Assert - 自动生成字段应该被忽略
            patient.Age.Should().Be(DateTime.Today.Year - 1995); // Age 是计算属性，由实体根据 BirthDate 计算
            patient.PinYinCode.Should().BeNull(); // 由业务逻辑生成
            patient.LastVisitTime.Should().BeNull();
            patient.VisitCount.Should().Be(0);
            patient.DisableReason.Should().BeNull();
            patient.Status.Should().Be(CommonStatus.Enabled); // Patient 实体默认值是 Enabled
        }

